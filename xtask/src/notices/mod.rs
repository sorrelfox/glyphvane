//! `cargo xtask notices [--check]`: the generated "Rust crates" section of
//! `packaging/THIRD-PARTY-NOTICES.txt`.
//!
//! The section lists every third-party crate linked into `glyphvane` and
//! `glyphvane-helper` (normal dependencies of `gv-app` and `gv-helper`, so
//! procedural macros are included and build and dev dependencies are not)
//! on each release target, with its version, declared licence, copyright
//! notices and the licence texts that apply to it. The texts come from the
//! licence, copying and notice files each crate ships: its own at the top
//! level, and those of components bundled in subfolders
//! (`THIRD_PARTY_LICENSES/`, vendored C sources), skipping tests, examples
//! and documentation. Each distinct text is printed once with the crates it
//! applies to. Copyright lines are taken out of a crate's own single-licence
//! files and listed per crate, so copies that differ only in copyright
//! lines, line wrapping or the Apache-2.0 appendix are printed once; other
//! files are printed whole. A crate that ships no licence file gets the
//! standard text of its licence (`licenses/`). Bundled licences that
//! `deny.toml` does not list are reported for review.
//!
//! One file covers all release targets: the executables embed it
//! (`glyphvane --licenses`, Help > Third-party licenses), so it cannot be
//! chosen per package. Crates linked on some targets only say so.
//!
//! `--check` fails when the section is not what the current `Cargo.lock`
//! produces, for example after a dependency was added; `cargo xtask ci` and
//! `cargo xtask package` run it. The output is deterministic: it depends
//! only on `Cargo.lock`, the crate sources and the files here.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
