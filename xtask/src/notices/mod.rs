/// The notices file, relative to the workspace root.
pub(crate) const NOTICES: &str = "packaging/THIRD-PARTY-NOTICES.txt";
const BEGIN: &str = "[BEGIN crate notices: generated by `cargo xtask notices`, do not edit]";
const END: &str = "[END crate notices]";

/// The release targets (`.github/workflows/release.yml`) and their names.
const TARGETS: &[(&str, &str)] = &[
    ("x86_64-unknown-linux-gnu", "Linux x86-64"),
    ("aarch64-unknown-linux-gnu", "Linux ARM64"),
    ("x86_64-pc-windows-msvc", "Windows x86-64"),
    ("aarch64-pc-windows-msvc", "Windows ARM64"),
];

/// The packages whose binaries ship: `glyphvane` and `glyphvane-helper`.
const ROOTS: &[&str] = &["gv-app", "gv-helper"];

