//! The IPC protocol between `glyphvane` and `glyphvane-helper`.
//!
//! Frames go over the helper's standard input and output: a little-endian
//! `u32` length, then a postcard-encoded [`Request`] or [`Response`].
//! Frames are capped at [`MAX_FRAME`] bytes in both directions. The first
//! exchange is a [`Hello`] in each direction: the app's version and
//! [`PROTOCOL`] must match the helper's, else the helper is from another
//! build (for example after a package upgrade while the app runs).

use std::io::{self, Read, Write};

use serde::{Deserialize, Serialize};

/// The protocol's version. Bump it whenever a type of this module changes.
pub const PROTOCOL: u32 = 4;

/// The largest frame, in bytes, in either direction.
pub const MAX_FRAME: u32 = 256 << 20;

/// The largest side of a drawn page ([`Job::Page`]), in pixels.
pub const MAX_PAGE_SIDE: u32 = 4096;

/// The largest side of a page drawn at a scale ([`Job::Render`]), in
/// pixels: hayro's sizes are `u16`, and wrap silently above 65,535.
pub const MAX_RENDER_SIDE: u32 = 16_384;

/// The most pixels of one page drawn at a scale ([`Job::Render`]): a
/// larger request is drawn smaller, keeping its proportions.
pub const MAX_RENDER_PIXELS: u64 = 24 << 20;

/// The most pixels an image of a page may have once decoded: hayro
/// decodes images at full size, so a page with a larger one is refused
/// before it is drawn.
pub const MAX_IMAGE_PIXELS: u64 = 100_000_000;

/// The largest text of a page ([`Job::Text`]) the parent accepts, in
/// bytes (its text and 16 bytes per character box).
pub const MAX_TEXT_BYTES: u64 = 16 << 20;

/// The version both sides announce.
pub const VERSION: &str = env!("CARGO_PKG_VERSION");

/// The handshake.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Hello {
    pub version: String,
    pub protocol: u32,
}

impl Hello {
    /// This build's handshake.
    pub fn ours() -> Self {
        Self {
            version: VERSION.to_owned(),
            protocol: PROTOCOL,
        }
    }
}

/// A message to the helper.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum Request {
    Hello(Hello),
    Job {
        id: u64,
        /// The parent's deadline, for the helper's information: the parent
        /// enforces it by killing the helper.
        deadline_ms: u64,
        /// The largest result the parent accepts, in bytes.
        max_output: u64,
        job: Job,
    },
}

/// A message from the helper.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum Response {
    Hello(Hello),
    Done {
        id: u64,
        result: Result<Output, String>,
    },
}

/// The work a helper does.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum Job {
    /// Compile a generated Typst document to PDF.
    Pdf(PdfJob),
    /// Draw a page of a PDF.
    Page(PageJob),
    /// Read a PDF and keep it for [`Job::Render`]: the answer is its page
    /// sizes ([`Output::Document`]).
    Open(OpenJob),
    /// Draw a page of the PDF [`Job::Open`] kept, at a scale. A helper
    /// that does not hold that PDF (a new one, or another PDF opened
    /// since) answers [`Output::NoDocument`]: open it again.
    Render(RenderJob),
    /// Read the text of a page of the PDF [`Job::Open`] kept, with each
    /// character's box ([`Output::Text`]); like [`Job::Render`], a helper
    /// that does not hold that PDF answers [`Output::NoDocument`].
    Text(TextJob),
    /// Misbehave on purpose, for the tests of the parent's limits.
    Fault(Fault),
}

/// Ways to misbehave ([`Job::Fault`]).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum Fault {
    /// Do nothing for this long, then answer.
    Sleep { ms: u64 },
    /// Exit at once, as a crash would.
    Exit,
    /// Allocate and touch this many megabytes.
    Allocate { mb: u64 },
}

/// A Typst document to compile: the main source and the files it reads,
/// all generated by the exporter.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct PdfJob {
    /// The main file (`/main.typ`).
    pub source: String,
    /// Virtual paths (`/assets/N.ext`) and their bytes; no other file can
    /// be read.
    pub assets: Vec<(String, Vec<u8>)>,
    /// Font families the document names; the helper loads the bundled
    /// faces of these families, else the installed ones.
    pub fonts: Vec<String>,
    /// More pages than this fail the job.
    pub max_pages: u32,
    /// The PDF's document identifier (stable for the same document).
    pub ident: String,
}

/// What a job produced.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum Output {
    Pdf(PdfOutput),
    Page(PageImage),
    /// The pages of a PDF [`Job::Open`] read.
    Document(DocInfo),
    /// The text of a page ([`Job::Text`]).
    Text(PageText),
    /// The helper does not hold the PDF a [`Job::Render`] or a
    /// [`Job::Text`] names.
    NoDocument,
    /// The answer of a [`Job::Fault`] that returned.
    Done,
}

/// A PDF to keep for drawing page by page ([`Job::Open`]).
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct OpenJob {
    /// The parent's name for this PDF (the same bytes, the same key).
    pub key: u64,
    pub pdf: Vec<u8>,
}

/// A page of the kept PDF to draw ([`Job::Render`]).
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct RenderJob {
    /// The key of the PDF ([`OpenJob::key`]).
    pub key: u64,
    /// The page, from 0.
    pub page: u32,
    /// Pixels per PDF point (1/72 inch).
    pub scale: f32,
    /// The most pixels of the image (at most [`MAX_RENDER_PIXELS`]): a
    /// larger page is drawn at a smaller scale.
    pub max_pixels: u64,
}

/// A page of the kept PDF whose text to read ([`Job::Text`]).
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct TextJob {
    /// The key of the PDF ([`OpenJob::key`]).
    pub key: u64,
    /// The page, from 0.
    pub page: u32,
}

/// The box of a character on its page, in PDF points from the page's top
/// left (as shown: crop box, rotated).
#[derive(Debug, Clone, Copy, Default, PartialEq, Serialize, Deserialize)]
pub struct TextBox {
    pub x0: f32,
    pub y0: f32,
    pub x1: f32,
    pub y1: f32,
}

/// The text of a page, in the content stream's order (column by column
/// on a page in two columns), with spaces and line ends between words and
/// lines; `boxes` has one box per character (`char`) of `text`.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct PageText {
    pub text: String,
    pub boxes: Vec<TextBox>,
}

impl PageText {
    /// Its size as the parent counts it against [`MAX_TEXT_BYTES`].
    pub fn bytes(&self) -> u64 {
        self.text.len() as u64 + 16 * self.boxes.len() as u64
    }
}

/// The size of a page as shown (its crop box, rotated), in PDF points.
#[derive(Debug, Clone, Copy, Default, PartialEq, Serialize, Deserialize)]
pub struct PageSize {
    pub width: f32,
    pub height: f32,
}

/// What [`Job::Open`] read.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct DocInfo {
    /// Every page's size, in order.
    pub pages: Vec<PageSize>,
}

/// A compiled PDF.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct PdfOutput {
    pub pdf: Vec<u8>,
    pub pages: u32,
    /// Typst's warnings, as text.
    pub warnings: Vec<String>,
}

/// A page of a PDF to draw, scaled to fit a box.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct PageJob {
    pub pdf: Vec<u8>,
    /// The page, from 0.
    pub page: u32,
    /// The box the image fits in, in pixels.
    pub max_width: u32,
    pub max_height: u32,
}

/// A drawn page: straight-alpha RGBA rows, top first, on white.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct PageImage {
    pub width: u32,
    pub height: u32,
    pub rgba: Vec<u8>,
    /// The number of pages of the PDF.
    pub pages: u32,
}

/// Writes one frame.
pub fn write_frame(w: &mut impl Write, payload: &[u8]) -> io::Result<()> {
    let n = u32::try_from(payload.len())
        .ok()
        .filter(|n| *n <= MAX_FRAME)
        .ok_or_else(|| io::Error::other("frame too large"))?;
    w.write_all(&n.to_le_bytes())?;
    w.write_all(payload)?;
    w.flush()
}

/// Reads one frame.
pub fn read_frame(r: &mut impl Read) -> io::Result<Vec<u8>> {
    let mut len = [0u8; 4];
    r.read_exact(&mut len)?;
    let n = u32::from_le_bytes(len);
    if n > MAX_FRAME {
        return Err(io::Error::other(format!("a frame of {n} bytes")));
    }
    let mut buf = vec![0u8; n as usize];
    r.read_exact(&mut buf)?;
    Ok(buf)
}

/// Encodes and writes `message`.
pub fn send<T: Serialize>(w: &mut impl Write, message: &T) -> io::Result<()> {
    let bytes = postcard::to_stdvec(message).map_err(io::Error::other)?;
    write_frame(w, &bytes)
}

/// Decodes a frame.
pub fn decode<'a, T: Deserialize<'a>>(frame: &'a [u8]) -> io::Result<T> {
    postcard::from_bytes(frame).map_err(io::Error::other)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn frames_round_trip_and_are_capped() {
        let mut buf = Vec::new();
        let job = Request::Job {
            id: 7,
            deadline_ms: 1000,
            max_output: 10,
            job: Job::Pdf(PdfJob {
                source: "#\"hi\";".into(),
                assets: vec![("/assets/0.png".into(), vec![1, 2, 3])],
                fonts: vec!["Inter".into()],
                max_pages: 5,
                ident: "x".into(),
            }),
        };
        send(&mut buf, &job).expect("send");
        let frame = read_frame(&mut buf.as_slice()).expect("read");
        let Request::Job { id, job, .. } = decode(&frame).expect("decode") else {
            panic!("a job");
        };
        assert_eq!(id, 7);
        assert!(matches!(job, Job::Pdf(p) if p.max_pages == 5));

        let text = Response::Done {
            id: 8,
            result: Ok(Output::Text(PageText {
                text: "Hi".into(),
                boxes: vec![TextBox::default(); 2],
            })),
        };
        let mut buf = Vec::new();
        send(&mut buf, &text).expect("send");
        let frame = read_frame(&mut buf.as_slice()).expect("read");
        let Response::Done { result, .. } = decode(&frame).expect("decode") else {
            panic!("an answer");
        };
        assert!(matches!(result, Ok(Output::Text(t)) if t.text == "Hi" && t.bytes() == 34));

        let mut huge = Vec::new();
        huge.extend_from_slice(&(MAX_FRAME + 1).to_le_bytes());
        assert!(read_frame(&mut huge.as_slice()).is_err());
    }
}
